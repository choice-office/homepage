/* 해시 route → Next 경로 매핑 */
export const routePath = (route: string, param?: string | null): string => {
	switch (route) {
		case "home":
			return "/";
		case "greeting":
			return "/greeting";
		case "profile":
			return "/members";
		case "location":
			return "/location";
		case "services":
			return "/services";
		case "service":
			return `/services/${param}`;
		case "reviews":
			return "/reviews";
		case "faq":
			return "/faq";
		case "blog":
			return "/blog";
		case "contact":
			return "/contact";
		default:
			return "/";
	}
};

